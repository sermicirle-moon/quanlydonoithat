    private void btnDNActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDNActionPerformed
        // TODO add your handling code here:
         String email = txtDN.getText();
        String password = new String(txtMk.getPassword());
        
        // Validate email
        String emailCheck = validateEmail.checkEmail(email);
        if (!emailCheck.equals("OK")) {
            JOptionPane.showMessageDialog(this,"Lỗi email: ");
            txtDN.requestFocus();
            return;
        }
        
        // Kiểm tra password có đạt tất cả yêu cầu không
        if (!validateEmail.isPasswordAllValid(password)) {
            JOptionPane.showMessageDialog(this,"Mật khẩu chưa đủ mạnh!");
            txtMk.requestFocus();
            return;
        }
        
        try {
            // Kiểm tra đăng nhập
            taikhoanDAO dao = new taikhoanDAO();
            if (dao.checkLogin(email, password)) {
            // Lấy thông tin user
            
                taikhoan currentUser = dao.getTaiKhoanByEmail(email);
                JOptionPane.showMessageDialog(this,"Đăng nhập thành công!");
                // Đóng form đăng nhập                
                mainmenu mainForm = new mainmenu();
                mainForm.setCurrentUser(currentUser); // Cần thêm phương thức này trong mainmenu
                mainForm.setVisible(true);
                this.dispose();
            } else {
                JOptionPane.showMessageDialog(this,"Sai email hoặc mật khẩu!");
                txtMk.setText("");
                txtMk.requestFocus();
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, 
                "Lỗi kết nối: " + e.getMessage(), 
                "Lỗi hệ thống", 
                JOptionPane.ERROR_MESSAGE);
        }
    
    }//GEN-LAST:event_btnDNActionPerformed

