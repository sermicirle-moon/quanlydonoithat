    private void btnDKActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDKActionPerformed
        // TODO add your handling code here:
        String email = txtTDN.getText();
        String password = new String(txtPass.getPassword());
        String hoten = txtHoten.getText();
        String sdt = txtSdt.getText();
        String role = (String) cbRole.getSelectedItem();
        
        // Validate email
        String emailCheck = validateEmail.checkEmail(email);
        if (!emailCheck.equals("OK")) {
            JOptionPane.showMessageDialog(this,"Lỗi email: ");
            txtTDN.requestFocus();
            return;
        }
        
        // Kiểm tra password có đạt tất cả yêu cầu không
        if (!validateEmail.isPasswordAllValid(password)) {
            JOptionPane.showMessageDialog(this,"Mật khẩu chưa đủ mạnh!");
            txtPass.requestFocus();
            return;
        }
        
        // Validate họ tên
        if (hoten.isEmpty() || hoten.length() < 2) {
            JOptionPane.showMessageDialog(this,"Họ tên phải có ít nhất 2 ký tự");
            txtHoten.requestFocus();
            return;
        }
        
        // Validate số điện thoại
        if (!validate.isInteger(sdt) || !validate.isValidPhoneNumber(sdt)) {
            JOptionPane.showMessageDialog(this,"Số điện thoại phải có 10 chữ số");
            txtSdt.requestFocus();
            return;
        }
        
        try {
            taikhoanDAO dao = new taikhoanDAO();
            
            // Kiểm tra email đã tồn tại
            if (dao.isEmailExists(email)) {
                JOptionPane.showMessageDialog(this,"Email đã tồn tại");
                txtTDN.requestFocus();
                return;
            }
            
            // Tạo đối tượng tài khoản
            taikhoan tk = new taikhoan();
            tk.setEmail(email);
            tk.setPass(password);
            tk.setName(hoten);
            tk.setRole(role);
            tk.setPhone(sdt);
            
            // Đăng ký
            if (dao.register(tk)) {
                JOptionPane.showMessageDialog(this,"Đăng ký thành công!");
                
                // Quay lại form đăng nhập
                closeRegisterDialog();
                
                // Điền email vào ô đăng nhập
                txtDN.setText(email);
                txtMk.requestFocus();
            } else {
                JOptionPane.showMessageDialog(this, "Đăng ký thất bại!" );
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this,"Lỗi: " + e.getMessage());
        }
    }//GEN-LAST:event_btnDKActionPerformed

